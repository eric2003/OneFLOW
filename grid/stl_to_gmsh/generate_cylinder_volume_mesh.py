"""Generate an analytic cut-cylinder surface reference and Gmsh fluid volume mesh."""
from __future__ import annotations

import argparse
import json
import math
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from grid.stl_import.analytic_cylinder import (  # noqa: E402
    build_cylinder_lateral_surface,
    write_ascii_stl,
)
from grid.stl_to_gmsh.converter import inspect_msh4  # noqa: E402


EXPECTED_GROUPS = {
    (2, "wall"), (2, "inflow"), (2, "outflow"), (3, "fluid_domain")
}


def build_cylinder_volume_geo(
    radius: float, cut_start: float, cut_end: float, mesh_size: float
) -> str:
    """Build a 3D OCC cylinder volume with user-defined inlet/outlet planes."""
    values = (radius, cut_start, cut_end, mesh_size)
    if not all(math.isfinite(value) for value in values):
        raise ValueError("cylinder and mesh parameters must be finite")
    if radius <= 0 or cut_start >= cut_end:
        raise ValueError("radius must be positive and cut_start must be less than cut_end")
    if mesh_size <= 0:
        raise ValueError("mesh_size must be positive")
    tolerance = max(radius, cut_end - cut_start, 1.0) * 1.0e-7
    return "\n".join((
        "// Generated by OneFLOW analytic cylinder cutting workflow.",
        'SetFactory("OpenCASCADE");',
        "Mesh.MshFileVersion = 4.1;",
        "Mesh.Binary = 0;",
        "Mesh.ElementOrder = 1;",
        f"Mesh.MeshSizeMin = {mesh_size:.17g};",
        f"Mesh.MeshSizeMax = {mesh_size:.17g};",
        f"Cylinder(1) = {{{cut_start:.17g}, 0, 0, "
        f"{(cut_end-cut_start):.17g}, 0, 0, {radius:.17g}}};",
        f"inlet() = Surface In BoundingBox "
        f"{{{cut_start-tolerance:.17g}, {-radius-tolerance:.17g}, "
        f"{-radius-tolerance:.17g}, {cut_start+tolerance:.17g}, "
        f"{radius+tolerance:.17g}, {radius+tolerance:.17g}}};",
        f"outlet() = Surface In BoundingBox "
        f"{{{cut_end-tolerance:.17g}, {-radius-tolerance:.17g}, "
        f"{-radius-tolerance:.17g}, {cut_end+tolerance:.17g}, "
        f"{radius+tolerance:.17g}, {radius+tolerance:.17g}}};",
        "all_surfaces() = Surface{:};",
        "wall() = all_surfaces();",
        "wall() -= inlet();",
        "wall() -= outlet();",
        'Physical Surface("wall") = {wall()};',
        'Physical Surface("inflow") = {inlet()};',
        'Physical Surface("outflow") = {outlet()};',
        'Physical Volume("fluid_domain") = {1};',
        "",
    ))


def _require_external_output(path: Path) -> Path:
    resolved = path.expanduser().resolve()
    try:
        resolved.relative_to(ROOT)
    except ValueError:
        return resolved
    raise ValueError(f"Generated files must stay outside the source repository: {resolved}")


def generate(
    output_directory: Path,
    gmsh: str,
    *,
    radius: float = 1.0,
    axis_start: float = -2.0,
    axis_end: float = 2.0,
    cut_start: float = -1.5,
    cut_end: float = 1.5,
    circumferential_divisions: int = 48,
    axial_divisions: int = 12,
    mesh_size: float = 0.2,
) -> dict:
    """Create the cut STL, independently inspect it, and generate a volume MSH."""
    output_directory = _require_external_output(output_directory)
    if not math.isfinite(axis_start) or not math.isfinite(axis_end):
        raise ValueError("cylinder axial extent must be finite")
    if not axis_start < cut_start < cut_end < axis_end:
        raise ValueError("cut planes must be strictly inside the cylinder and ordered")
    if not gmsh:
        raise ValueError("Gmsh executable was not specified or discovered")
    output_directory.mkdir(parents=True, exist_ok=True)
    cut_stl = output_directory / "cylinder_cut_surface.stl"
    cut_report_path = output_directory / "cut_report.json"
    stage_a_report_path = output_directory / "stage_a_report.json"
    geo_path = output_directory / "cylinder_fluid_domain.geo"
    msh_path = output_directory / "cylinder_fluid_domain.msh"
    report_path = output_directory / "generation_report.json"
    msh_path.unlink(missing_ok=True)
    report_path.unlink(missing_ok=True)

    triangles = build_cylinder_lateral_surface(
        radius, axis_start, axis_end, cut_start, cut_end,
        circumferential_divisions, axial_divisions,
    )
    write_ascii_stl(cut_stl, triangles)
    cut_report = {
        "operation": "analytic_cylinder_lateral_cut",
        "asset_id": "geometry.cylinder.internal_flow",
        "source_kind": "explicit_analytic_definition",
        "axis": "X",
        "radius": radius,
        "axis_extent": [axis_start, axis_end],
        "cut_planes": [cut_start, cut_end],
        "end_caps_generated": False,
        "triangle_count": len(triangles),
        "output_stl": str(cut_stl),
    }
    cut_report_path.write_text(
        json.dumps(cut_report, indent=2) + "\n", encoding="utf-8", newline="\n"
    )
    project_manifest = {
        "schema": "oneflow.cylinder-cut-project", "version": 1,
        "geometry_asset_id": "geometry.cylinder.internal_flow",
        "input_stl": cut_stl.name,
    }
    (output_directory / "project.json").write_text(
        json.dumps(project_manifest, indent=2) + "\n", encoding="utf-8", newline="\n"
    )

    inspector = ROOT / "grid" / "stl_import" / "inspect.py"
    inspect_command = [
        sys.executable, str(inspector), "--input", str(cut_stl),
        "--output", str(stage_a_report_path),
    ]
    inspected = subprocess.run(
        inspect_command, cwd=ROOT, capture_output=True, text=True, check=False
    )
    if inspected.returncode != 0:
        raise RuntimeError(
            "Stage A inspection failed: " + (inspected.stderr or inspected.stdout)
        )
    stage_a = json.loads(stage_a_report_path.read_text(encoding="utf-8"))
    quality = stage_a["surface_quality"]
    boundary = quality["boundary"]
    expected_vertices = circumferential_divisions
    if (
        quality["status"] != "warning"
        or quality["closed"]
        or not quality["edge_manifold"]
        or not quality["consistently_oriented"]
        or quality["connected_component_count"] != 1
        or boundary["boundary_loop_count"] != 2
        or boundary["boundary_component_vertex_counts"]
        != [expected_vertices, expected_vertices]
        or quality["non_manifold_edge_count"] != 0
    ):
        raise RuntimeError("Stage A did not confirm one open cylinder surface with two boundary loops")

    geo_path.write_text(
        build_cylinder_volume_geo(radius, cut_start, cut_end, mesh_size),
        encoding="ascii", newline="\n",
    )
    command = [gmsh, str(geo_path), "-3", "-format", "msh4", "-o", str(msh_path)]
    result = subprocess.run(
        command, cwd=output_directory, capture_output=True, text=True, check=False
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout or "").strip()
        raise RuntimeError(f"Gmsh failed with exit code {result.returncode}: {detail[-4000:]}")
    mesh = inspect_msh4(msh_path)
    groups = {(item["dimension"], item["name"]) for item in mesh["physical_groups"]}
    if groups != EXPECTED_GROUPS:
        raise RuntimeError(
            f"Gmsh Physical Groups {sorted(groups)} do not match {sorted(EXPECTED_GROUPS)}"
        )
    if mesh["tetrahedron_elements"] <= 0 or mesh["triangle_elements"] <= 0:
        raise RuntimeError("Gmsh mesh must contain boundary triangles and tetrahedral volume cells")

    report = {
        "schema": "oneflow.analytic-cylinder-cut-mesh",
        "version": 1,
        "parameters": {
            "radius": radius, "axis_start": axis_start, "axis_end": axis_end,
            "cut_start": cut_start, "cut_end": cut_end,
            "circumferential_divisions": circumferential_divisions,
            "axial_divisions": axial_divisions, "mesh_size": mesh_size,
        },
        "stages": {
            "analytic_surface_cut": "PASS",
            "stage_a_boundary_loop_inspection": "PASS",
            "gmsh_analytic_volume_mesh": "PASS",
            "physical_group_validation": "PASS",
        },
        "cut_surface": str(cut_stl),
        "project_manifest": str(output_directory / "project.json"),
        "stage_a_report": str(stage_a_report_path),
        "geometry_script": str(geo_path),
        "volume_mesh": str(msh_path),
        "mesh_summary": {
            "nodes": mesh["nodes"],
            "elements": mesh["elements"],
            "triangle_elements": mesh["triangle_elements"],
            "tetrahedron_elements": mesh["tetrahedron_elements"],
            "physical_groups": mesh["physical_groups"],
        },
    }
    report_path.write_text(
        json.dumps(report, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8", newline="\n",
    )
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-directory", type=Path, required=True)
    parser.add_argument("--gmsh", default=shutil.which("gmsh") or shutil.which("gmsh.exe"))
    parser.add_argument("--radius", type=float, default=1.0)
    parser.add_argument("--axis-start", type=float, default=-2.0)
    parser.add_argument("--axis-end", type=float, default=2.0)
    parser.add_argument("--cut-start", type=float, default=-1.5)
    parser.add_argument("--cut-end", type=float, default=1.5)
    parser.add_argument("--circumferential-divisions", type=int, default=48)
    parser.add_argument("--axial-divisions", type=int, default=12)
    parser.add_argument("--mesh-size", type=float, default=0.2)
    args = parser.parse_args(argv)
    try:
        report = generate(
            args.output_directory, args.gmsh, radius=args.radius,
            axis_start=args.axis_start, axis_end=args.axis_end,
            cut_start=args.cut_start, cut_end=args.cut_end,
            circumferential_divisions=args.circumferential_divisions,
            axial_divisions=args.axial_divisions, mesh_size=args.mesh_size,
        )
    except (OSError, ValueError, KeyError, RuntimeError, json.JSONDecodeError) as error:
        parser.exit(2, f"cylinder_cut_mesh: {error}\n")
    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
